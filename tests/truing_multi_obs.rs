    let load = test_load();
    // 275/550/825 m ~= 300/600/900 yd.
    let drops: Vec<(f64, f64)> = [(275.0, 300.0), (550.0, 600.0), (825.0, 900.0)]
        .iter()
        .map(|&(m, yd)| (m, forward_drop_mil(&load, yd)))
        .collect();
    let out = run_true_velocity(&[
        "true-velocity",
        "--measured-drop",
        &format!("{:.6}", drops[0].1),
        "--range",
        "275",
        "--observed",
        &format!("550:{:.6}", drops[1].1),
        "--observed",
        &format!("825:{:.6}", drops[2].1),
        "--bc",
        "0.45",
        "--drag-model",
        "g1",
        "--mass",
        "168",
        "--diameter",
        "0.308",
        "--units",
        "metric",
        "--output",
        "json",
    ]);
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    let v: Value = serde_json::from_slice(&out.stdout).unwrap();
